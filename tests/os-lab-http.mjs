import assert from 'node:assert/strict';
import {randomBytes,createHash,randomUUID} from 'node:crypto';
import {chromium} from 'playwright';
import {Pool} from 'pg';

if(process.env.GITHUB_ACTIONS!=='true'||process.env.BLINKO_CI_DISPOSABLE!=='yes')throw Error('Disposable CI only');
const origin='https://127.0.0.1:3211';
const owner=new Pool({host:'127.0.0.1',port:5432,database:'blinko_sandbox',user:'sandbox_owner',password:'synthetic-ci-only'});
const codes={operator:randomBytes(32).toString('hex'),admin:randomBytes(32).toString('hex')};
const actor={operator:'00000000-0000-4000-8000-000000000011',admin:'00000000-0000-4000-8000-000000000013'};
for(const k of Object.keys(codes))await owner.query("INSERT INTO os_lab.access_codes(code_hash,member_id,expires_at) VALUES($1,$2,now()+interval '10 minutes')",[createHash('sha256').update(codes[k]).digest('hex'),actor[k]]);
await owner.end();
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({ignoreHTTPSErrors:true});
const page=await context.newPage();
const endpoint=origin+'/api/os-lab/projects';
const session=origin+'/api/os-lab/session';
const request=async(method,url,data,status=200,extra={})=>{
 const res=await context.request.fetch(url,{method,headers:{origin,...extra},...(data===undefined?{}:{data})});
 assert.equal(res.status(),status,method+' '+new URL(url).pathname);
 const body=await res.json();assert.equal(body.ok,status<400);
 return {body,res};
};
try{
 await request('GET',endpoint,undefined,401);
 await request('POST',session,{code:codes.operator},403,{origin:'https://invalid.example'});
 await page.goto(origin+'/os-workspace/login');
 await page.getByLabel('Código de acesso').fill(codes.operator);
 await page.getByRole('button',{name:'Entrar',exact:true}).click();
 await page.waitForURL('**/os-workspace');
 await page.getByText('Registros consultados.',{exact:true}).waitFor();
 const cookies=await context.cookies();const cookie=cookies.find(c=>c.name==='blinko_os_lab_session');
 assert.ok(cookie?.httpOnly&&cookie.secure&&cookie.sameSite==='Strict');
 await request('POST',session,{code:codes.operator},401);
 const company='Empresa fictícia HTTP '+randomUUID().slice(0,8);
 await page.getByLabel('Nome fictício').fill(company);
 await page.getByLabel('Consentimento simulado').check();
 await page.getByRole('button',{name:'Registrar oportunidade'}).click();
 await page.getByRole('option',{name:new RegExp(company)}).waitFor({state:'attached'});
 const leads=(await request('GET',endpoint+'?scope=crm')).body.data;
 const lead=leads.find(l=>l.display_name===company);assert.ok(lead);
 await page.reload();
 await page.getByRole('option',{name:new RegExp(company)}).waitFor({state:'attached'});
 await page.getByLabel('Lead ativo').selectOption(lead.id);
 await page.getByRole('button',{name:'Concluir triagem'}).click();
 await page.getByText(/Triagem: completa/).waitFor();
 const stages=['triagem','contato','reuniao','proposta','diagnostico'];
 for(let i=0;i<4;i++)await request('PUT',endpoint,{type:'lead_move',id:lead.id,expectedStage:stages[i],nextStage:stages[i+1]});
 const projectId=randomUUID();
 const contracted=(await request('PUT',endpoint,{type:'lead_contract',id:lead.id,projectId,confirmed:true})).body.data.id;
 assert.equal(contracted,projectId);
 const e=(await request('POST',endpoint,{projectId,pillar:0,kind:'fact',summary:'Synthetic HTTP evidence'},201)).body.data;
 await request('PATCH',endpoint,{evidenceId:e.id,reviewed:true,reason:'Synthetic denied review'},403);
 const op=(await request('GET',endpoint+'?scope=operations&project='+projectId)).body.data;
 assert.equal(op.finance,null);
 await page.getByRole('button',{name:'Sair',exact:true}).click();
 await page.waitForURL('**/os-workspace/login');
 const revoked=await request('GET',endpoint,undefined,401,{cookie:cookie.name+'='+cookie.value});
 assert.equal(revoked.body.error,'session_inactive');
 console.log('PASS operator login, secure cookie, persistent CRM, project and logout');
 await page.getByLabel('Código de acesso').fill(codes.admin);
 await page.getByRole('button',{name:'Entrar',exact:true}).click();
 await page.waitForURL('**/os-workspace');
 await page.getByText('Registros consultados.',{exact:true}).waitFor();
 await request('PATCH',endpoint,{evidenceId:e.id,reviewed:true,reason:'Synthetic review'});
 await request('PUT',endpoint,{type:'score',projectId,pillar:0,value:2,evidenceId:e.id});
 const actionId=randomUUID();
 await request('PUT',endpoint,{type:'action',id:actionId,projectId,evidenceId:e.id,title:'Synthetic action',owner:'Equipe',due:'2026-12-15',gravity:4,urgency:4,tendency:3});
 await request('PUT',endpoint,{type:'completion',id:actionId,done:true});
 const data=(await request('GET',endpoint+'?scope=operations&project='+projectId)).body.data;
 assert.ok(data.scores.some(s=>s.pillar===0&&s.eligible&&s.value===2));
 assert.ok(data.actions.some(a=>a.id===actionId&&a.gut===48&&a.done));
 assert.ok(data.finance!==null);
 await page.getByLabel('Projeto',{exact:true}).selectOption(projectId);
 await page.getByText(/1\/10 pilares avaliados/).waitFor();
 await page.getByText('Synthetic action',{exact:true}).first().waitFor();
 await page.reload();
 await page.getByText('Registros consultados.',{exact:true}).waitFor();
 await page.getByLabel('Projeto',{exact:true}).selectOption(projectId);
 await page.getByText(/1\/10 pilares avaliados/).waitFor();
 await page.getByText('Synthetic action',{exact:true}).first().waitFor();
 console.log('PASS administrator review, radar and action persistence after reload');
}finally{await browser.close();}
